GO_TYPES = {
    "string": "string", "double": "float64", "uint64": "uint64",
    "uint32": "uint32", "bool": "bool", "timestamp": "int64",
    "map<string,string>": "map[string]string",
}
PY_TYPES = {
    "string": "str", "double": "float", "uint64": "int", "uint32": "int",
    "bool": "bool", "timestamp": "int", "map<string,string>": "dict[str, str]",
}
PY_DEFAULTS = {
    "string": '""', "double": "0.0", "uint64": "0", "uint32": "0",
    "bool": "False", "timestamp": "0",
}
PROTO_TYPES = {
    "string": "string", "double": "double", "uint64": "uint64",
    "uint32": "uint32", "bool": "bool",
    "timestamp": "google.protobuf.Timestamp",
    "map<string,string>": "map<string, string>",
}


def go_type(t: str) -> str:
    if t.startswith("enum:"):
        return t.split(":", 1)[1]
    if t.startswith("repeated:"):
        return "[]" + t.split(":", 1)[1]
    return GO_TYPES[t]


def py_type(t: str) -> str:
    if t.startswith("enum:"):
        return "int"
    if t.startswith("repeated:"):
        return f'list["{t.split(":", 1)[1]}"]'
    return PY_TYPES[t]


def proto_type(t: str) -> str:
    if t.startswith("enum:"):
        return t.split(":", 1)[1]
    if t.startswith("repeated:"):
        return "repeated " + t.split(":", 1)[1]
    return PROTO_TYPES[t]


