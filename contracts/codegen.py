def emit(path: Path, content: str, check: bool, stale: list[str]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    existing = path.read_text(encoding="utf-8") if path.exists() else None
    if existing == content:
        return
    if check:
        stale.append(str(path.relative_to(ROOT)))
        return
    path.write_text(content, encoding="utf-8", newline="\n")
    print(f"wrote {path.relative_to(ROOT)}")


def validate(reg: dict) -> None:
    """Fail loudly on registry mistakes that would otherwise surface at runtime."""
    seen: set[str] = set()
    keys = {m["key"] for m in reg["metrics"]}
    for m in reg["metrics"]:
        k = m["key"]
        if k in seen:
            sys.exit(f"duplicate metric key: {k}")
        seen.add(k)
        if k != k.lower() or " " in k:
            sys.exit(f"metric key must be lower snake_case: {k}")
        if m["value_type"] not in ("gauge", "counter", "delta", "bool", "text"):
            sys.exit(f"{k}: bad value_type {m['value_type']}")
        if "min_valid" in m and "max_valid" in m and m["min_valid"] > m["max_valid"]:
            sys.exit(f"{k}: min_valid > max_valid")
        ro = m.get("rate_of")
        if ro:
            if ro not in keys:
                sys.exit(f"{k}: rate_of references unknown metric {ro}")
            if m["value_type"] != "gauge":
                sys.exit(f"{k}: a rate_of metric must be a gauge")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true",
                    help="do not write; exit 1 if any output is stale")
    args = ap.parse_args()

    schema = load(CONTRACTS / "schema" / "messages_v1.yaml")
    reg = load(CONTRACTS / "metrics" / "registry.yaml")
    validate(reg)

    stale: list[str] = []
    emit(ROOT / "collector/pkg/models/messages_gen.go", gen_go_messages(schema), args.check, stale)
    emit(ROOT / "collector/pkg/models/metrics_gen.go", gen_go_metrics(reg), args.check, stale)
    emit(ROOT / "backend/app/contracts/messages_gen.py", gen_py_messages(schema), args.check, stale)
    emit(ROOT / "backend/app/core/metrics_gen.py", gen_py_metrics(reg), args.check, stale)
    emit(ROOT / "backend/app/core/mappings_gen.py",
         gen_py_mapping_groups(mapping_groups()), args.check, stale)
    emit(ROOT / "frontend/src/lib/metrics.gen.ts", gen_ts_metrics(reg), args.check, stale)
    emit(CONTRACTS / "proto/dcim/telemetry/v1/telemetry.proto", gen_proto(schema), args.check, stale)

    if stale:
        print("generated code is stale; run `python contracts/codegen.py`:", file=sys.stderr)
        for s in stale:
            print(f"  {s}", file=sys.stderr)
        return 1
    if args.check:
        print("generated code is up to date")
    return 0


