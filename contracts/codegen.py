# protobuf IDL (emitted for the future transport; nothing consumes it yet)
# --------------------------------------------------------------------------

def gen_proto(schema: dict) -> str:
    out = ["// Code generated by contracts/codegen.py. DO NOT EDIT.",
           "//",
           "// Emitted for the eventual protobuf transport. The wire format today is",
           "// msgpack keyed by field name - see docs/05-telemetry-contract.md.",
           'syntax = "proto3";', "",
           f"package {schema['package']};", "",
           'import "google/protobuf/timestamp.proto";', ""]

    for ename, edef in schema["enums"].items():
        out.append(f"enum {ename} {{")
        prefix = "".join("_" + c if c.isupper() else c.upper()
                         for c in ename).lstrip("_")
        for i, v in enumerate(edef["values"]):
            out.append(f"  {prefix}_{v} = {i};")
        out.append("}")
        out.append("")

    for mname, mdef in schema["messages"].items():
        if mdef.get("doc"):
            out.append(f"// {mdef['doc']}")
        out.append(f"message {mname} {{")
        for f in mdef["fields"]:
            doc = f"  // {f['doc']}" if f.get("doc") else ""
            out.append(f"  {proto_type(f['type'])} {f['name']} = {f['tag']};{doc}")
        out.append("}")
        out.append("")
    return "\n".join(out)


