#!/usr/bin/env python3
"""Generate Go, Python and TypeScript code from the contract definitions.

Deliberately depends on nothing but PyYAML: the contract must be regenerable on
a laptop with no protoc, no Go toolchain and no network. Run it with:

    python contracts/codegen.py            # write generated files
    python contracts/codegen.py --check    # exit 1 if anything is stale (CI)

Outputs
-------
    collector/pkg/models/messages_gen.go
    collector/pkg/models/metrics_gen.go
    backend/app/contracts/messages_gen.py
    backend/app/core/metrics_gen.py
    frontend/src/lib/metrics.gen.ts
    contracts/proto/dcim/telemetry/v1/telemetry.proto

Wire format
-----------
msgpack maps keyed by field NAME. Timestamps are int64 microseconds since the
Unix epoch, UTC, with 0 meaning unset - chosen over a language-native datetime
so that Go and Python cannot disagree about timezone handling. Unknown keys are
ignored on decode, which gives the forward compatibility protobuf tags would.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

try:
    import yaml
except ImportError:  # pragma: no cover - operator-facing message
    sys.exit("PyYAML is required: pip install pyyaml")

ROOT = Path(__file__).resolve().parent.parent
CONTRACTS = ROOT / "contracts"

BANNER = "// Code generated by contracts/codegen.py. DO NOT EDIT."
BANNER_PY = "# Code generated by contracts/codegen.py. DO NOT EDIT."

# Words that must keep their canonical casing when snake_case becomes CamelCase.
INITIALISMS = {
    "id": "ID", "ip": "IP", "cpu": "CPU", "url": "URL", "api": "API",
    "oid": "OID", "ms": "Ms", "bps": "Bps", "psu": "PSU", "pdu": "PDU",
    "ups": "UPS", "snmp": "SNMP", "gnmi": "GNMI", "http": "HTTP",
}


def camel(name: str) -> str:
    """snake_case -> CamelCase, honouring Go initialism conventions."""
    return "".join(INITIALISMS.get(p.lower(), p.capitalize()) for p in name.split("_"))


def align(rows: list[list[str]], indent: str = "	") -> list[str]:
    """Pad columns so the output is gofmt-clean without running gofmt.

    gofmt aligns runs of consecutive similar lines into columns. Reproducing
    that here keeps the generator toolchain-free (the whole point of writing it
    in Python) while still emitting code a Go reviewer would accept.
    """
    if not rows:
        return []
    width = max(len(r) for r in rows)
    padded = [r + [""] * (width - len(r)) for r in rows]
    widths = [max(len(r[c]) for r in padded) for c in range(width)]
    out = []
    for r in padded:
        cells = [r[c].ljust(widths[c]) for c in range(width - 1)]
        cells.append(r[-1])
        out.append((indent + " ".join(cells)).rstrip())
    return out


def align_struct(rows: list[list[str]]) -> list[str]:
    """Render struct fields as [name, type, tag, comment], gofmt-style.

    Name and type align across the whole struct, but the trailing-comment
    column aligns only across a RUN of consecutive commented lines - a field
    without a comment breaks the run. That is gofmt's actual rule, and
    reproducing it is what keeps generated code out of `gofmt -l`.
    """
    if not rows:
        return []
    w_name = max(len(r[0]) for r in rows)
    w_type = max(len(r[1]) for r in rows)

    out: list[str] = []
    i = 0
    while i < len(rows):
        if not rows[i][3]:
            r = rows[i]
            out.append(f"\t{r[0].ljust(w_name)} {r[1].ljust(w_type)} {r[2]}")
            i += 1
            continue
        run = []
        while i < len(rows) and rows[i][3]:
            run.append(rows[i])
            i += 1
        w_tag = max(len(r[2]) for r in run)
        for r in run:
            out.append(
                f"\t{r[0].ljust(w_name)} {r[1].ljust(w_type)} "
                f"{r[2].ljust(w_tag)} {r[3]}")
    return out


def load(path: Path) -> dict:
    with path.open(encoding="utf-8") as fh:
        return yaml.safe_load(fh)


