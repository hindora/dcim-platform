def gen_go_metrics(reg: dict) -> str:
    out = [BANNER, "", "package models", "",
           "// Canonical metric registry, generated from contracts/metrics/registry.yaml.",
           "// A metric key absent from MetricDefs is a hard validation failure at emit time.",
           "", "type MetricDef struct {"]
    out += align([
        ["Key", "string"], ["DisplayName", "string"], ["Unit", "string"],
        ["ValueType", "string"], ["Aggregation", "string"],
        ["MinValid", "float64"], ["MaxValid", "float64"],
        ["HasMin", "bool"], ["HasMax", "bool"], ["StaleAfterS", "int"],
        ["Hot", "bool"], ["Group", "string"], ["RateOf", "string"],
        ["RateScale", "float64"],
    ])
    out += ["}", "", "const ("]
    out += align([[f'Metric{camel(m["key"])}', f'= "{m["key"]}"']
                  for m in reg["metrics"]])
    out.append(")")
    out.append("")
    out.append("var MetricDefs = map[string]MetricDef{")
    for m in reg["metrics"]:
        has_min = "min_valid" in m
        has_max = "max_valid" in m
        out.append(f'\t"{m["key"]}": {{')
        out.append(f'\t\tKey: "{m["key"]}", DisplayName: "{m["display_name"]}", Unit: "{m["unit"]}",')
        out.append(f'\t\tValueType: "{m["value_type"]}", Aggregation: "{m.get("aggregation", "avg")}",')
        out.append(f'\t\tMinValid: {float(m.get("min_valid", 0)):g}, HasMin: {str(has_min).lower()},')
        out.append(f'\t\tMaxValid: {float(m.get("max_valid", 0)):g}, HasMax: {str(has_max).lower()},')
        out.append(f'\t\tStaleAfterS: {m.get("stale_after_s", 300)}, Hot: {str(bool(m.get("hot"))).lower()},')
        out.append(f'\t\tGroup: "{m.get("group", "")}", RateOf: "{m.get("rate_of", "")}", '
                   f'RateScale: {float(m.get("rate_scale", 1)):g},')
        out.append("\t},")
    out.append("}")
    out.append("")
    out.append("// MetricGroups maps a poll-profile group name to its metric keys.")
    groups: dict[str, list[str]] = {}
    for m in reg["metrics"]:
        groups.setdefault(m.get("group", "other"), []).append(m["key"])
    out.append("var MetricGroups = map[string][]string{")
    out += align([[f'"{g}":', "{" + ", ".join(f'"{k}"' for k in keys) + "},"]
                  for g, keys in sorted(groups.items())])
    out.append("}")
    out.append("")
    return "\n".join(out)


def gen_py_metrics(reg: dict) -> str:
    out = [BANNER_PY,
           '"""Canonical metric registry, generated from contracts/metrics/registry.yaml."""',
           "from __future__ import annotations", "",
           "from dataclasses import dataclass", "", "",
           "@dataclass(frozen=True, slots=True)",
           "class MetricDef:",
           "    key: str",
           "    display_name: str",
           "    unit: str",
           "    value_type: str",
           "    aggregation: str",
           "    min_valid: float | None",
           "    max_valid: float | None",
           "    stale_after_s: int",
           "    hot: bool",
           "    group: str",
           "    rate_of: str | None",
           "    rate_scale: float",
           "    device_types: tuple[str, ...]",
           "", "", "METRICS: dict[str, MetricDef] = {"]
    for m in reg["metrics"]:
        dts = ", ".join(f'"{d}"' for d in m.get("device_types", []))
        dts = f"({dts},)" if dts else "()"
        out.append(f'    "{m["key"]}": MetricDef(')
        out.append(f'        key="{m["key"]}", display_name="{m["display_name"]}", unit="{m["unit"]}",')
        out.append(f'        value_type="{m["value_type"]}", aggregation="{m.get("aggregation", "avg")}",')
        out.append(f'        min_valid={m.get("min_valid", None)!r}, max_valid={m.get("max_valid", None)!r},')
        out.append(f'        stale_after_s={m.get("stale_after_s", 300)}, hot={bool(m.get("hot"))!r},')
        out.append(f'        group="{m.get("group", "")}", rate_of={m.get("rate_of", None)!r}, '
                   f'rate_scale={float(m.get("rate_scale", 1))!r},')
        out.append(f'        device_types={dts},')
        out.append("    ),")
    out.append("}")
    out.append("")
    out.append("HOT_METRICS = tuple(k for k, m in METRICS.items() if m.hot)")
    out.append("COUNTER_METRICS = tuple(k for k, m in METRICS.items() if m.value_type == 'counter')")
    out.append("# counter key -> the gauge key its rate is written to")
    out.append("RATE_TARGETS = {m.rate_of: k for k, m in METRICS.items() if m.rate_of}")
    out.append("")
    return "\n".join(out)


def mapping_groups() -> dict[str, list[str]]:
    """Named profile blocks a poll profile's `metric_groups` can select.

    SNMP only, and that is not an omission. `MetricGroups` is read in exactly
    one place in the collector - adapters/snmp/snmp.go - so a group named on a
    profile used by any other protocol selects nothing. gNMI subscribes from
    its own mapping file, BACnet reads its object map, Modbus its register
    templates; none of them consults the profile.

    Which makes the seeded `gnmi-stream` profile's {interfaces} group
    decorative: it reads like configuration and changes nothing. Generating
    this list is what lets the API say so instead of accepting a group that
    will never be looked up.
    """
    doc = load(CONTRACTS / "mappings" / "snmp" / "standard.yaml")
    return {"snmp": [p["name"] for p in doc.get("profiles", [])]}


def gen_py_mapping_groups(groups: dict[str, list[str]]) -> str:
    out = [BANNER_PY,
           '"""Mapping profile groups, generated from contracts/mappings/*."""',
           "from __future__ import annotations", "", "",
           "#: protocol -> the group names a poll profile may select.",
           "#:",
           "#: SNMP is the only entry because MetricGroups is read in exactly",
           "#: one place in the collector, the SNMP adapter. gNMI subscribes",
           "#: from its own mapping file, BACnet reads its object map and",
           "#: Modbus its register templates - a group named on a profile used",
           "#: by any of those selects nothing at all.",
           "MAPPING_GROUPS: dict[str, tuple[str, ...]] = {"]
    for protocol, names in sorted(groups.items()):
        joined = ", ".join(f'"{n}"' for n in names)
        out.append(f'    "{protocol}": ({joined},),' if names
                   else f'    "{protocol}": (),')
    out.append("}")
    out.append("")
    out.append("#: Every group name known to any protocol.")
    out.append("ALL_GROUPS = frozenset(g for gs in MAPPING_GROUPS.values() "
               "for g in gs)")
    out.append("")
    return "\n".join(out)


def gen_ts_metrics(reg: dict) -> str:
    keys = [m["key"] for m in reg["metrics"]]
    out = ["// Code generated by contracts/codegen.py. DO NOT EDIT.",
           "",
           "export type MetricKey =",
           *[f"  | '{k}'" for k in keys],
           "  ;",
           "",
           "export interface MetricDef {",
           "  key: MetricKey;",
           "  displayName: string;",
           "  unit: string;",
           "  valueType: 'gauge' | 'counter' | 'delta' | 'bool' | 'text';",
           "  aggregation: string;",
           "  minValid: number | null;",
           "  maxValid: number | null;",
           "  staleAfterS: number;",
           "  hot: boolean;",
           "  group: string;",
           "}",
           "",
           "export const METRICS: Record<MetricKey, MetricDef> = {"]
    for m in reg["metrics"]:
        out.append(f"  '{m['key']}': {{")
        out.append(f"    key: '{m['key']}', displayName: {m['display_name']!r}.replace(/^'|'$/g, ''),")
        out.append(f"    unit: '{m['unit']}', valueType: '{m['value_type']}',")
        out.append(f"    aggregation: '{m.get('aggregation', 'avg')}',")
        out.append(f"    minValid: {m.get('min_valid', 'null') if 'min_valid' in m else 'null'},")
        out.append(f"    maxValid: {m.get('max_valid', 'null') if 'max_valid' in m else 'null'},")
        out.append(f"    staleAfterS: {m.get('stale_after_s', 300)}, hot: {str(bool(m.get('hot'))).lower()},")
        out.append(f"    group: '{m.get('group', '')}',")
        out.append("  },")
    out.append("};")
    out.append("")
    out.append("export const HOT_METRICS = (Object.keys(METRICS) as MetricKey[])")
    out.append("  .filter((k) => METRICS[k].hot);")
    out.append("")
    return "\n".join(out)


