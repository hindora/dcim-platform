def gen_py_messages(schema: dict) -> str:
    out = [BANNER_PY, '"""Canonical telemetry contract, generated from '
           'contracts/schema/messages_v1.yaml.',
           "",
           "Timestamps are int microseconds since the Unix epoch, UTC; 0 means unset.",
           "Use ``ts_to_dt`` / ``dt_to_ts`` rather than converting by hand.",
           '"""',
           "from __future__ import annotations", "",
           "from dataclasses import dataclass, field, fields as dc_fields",
           "from datetime import datetime, timezone",
           "from enum import IntEnum",
           "from typing import Any", "", ""]

    out += [
        "def ts_to_dt(us: int) -> datetime | None:",
        '    """Contract microseconds -> aware UTC datetime (None when unset)."""',
        "    if not us:",
        "        return None",
        "    return datetime.fromtimestamp(us / 1_000_000, tz=timezone.utc)",
        "", "",
        "def dt_to_ts(dt: datetime | None) -> int:",
        '    """Aware datetime -> contract microseconds (0 when None)."""',
        "    if dt is None:",
        "        return 0",
        "    if dt.tzinfo is None:",
        "        dt = dt.replace(tzinfo=timezone.utc)",
        "    return int(dt.timestamp() * 1_000_000)",
        "", "",
    ]

    for ename, edef in schema["enums"].items():
        out.append(f"class {ename}(IntEnum):")
        for i, v in enumerate(edef["values"]):
            out.append(f"    {v} = {i}")
        out.append("")
        out.append("")

    out += [
        "class _Msg:",
        '    """Mixin: msgpack-map codec keyed by field name, tolerant of unknown keys."""',
        "",
        "    def to_dict(self) -> dict[str, Any]:",
        "        out: dict[str, Any] = {}",
        "        for f in dc_fields(self):",
        "            v = getattr(self, f.name)",
        "            if v in (None, 0, 0.0, '', False) or (isinstance(v, (dict, list)) and not v):",
        "                continue  # omitempty, matching the Go encoder",
        "            if isinstance(v, list):",
        "                out[f.name] = [i.to_dict() if hasattr(i, 'to_dict') else i for i in v]",
        "            elif hasattr(v, 'to_dict'):",
        "                out[f.name] = v.to_dict()",
        "            else:",
        "                out[f.name] = int(v) if isinstance(v, IntEnum) else v",
        "        return out",
        "",
        "    @classmethod",
        "    def from_dict(cls, d: dict[str, Any]):",
        "        kwargs: dict[str, Any] = {}",
        "        nested = getattr(cls, '_nested', {})",
        "        for f in dc_fields(cls):",
        "            if f.name not in d:",
        "                continue  # absent == default; forward compatible",
        "            v = d[f.name]",
        "            sub = nested.get(f.name)",
        "            if sub is not None and isinstance(v, list):",
        "                v = [sub.from_dict(i) if isinstance(i, dict) else i for i in v]",
        "            kwargs[f.name] = v",
        "        return cls(**kwargs)",
        "", "",
    ]

    for mname, mdef in schema["messages"].items():
        out.append("@dataclass(slots=True)")
        out.append(f"class {mname}(_Msg):")
        if mdef.get("doc"):
            out.append(f'    """{mdef["doc"]}"""')
        nested = {}
        for f in mdef["fields"]:
            t = f["type"]
            pt = py_type(t)
            if t.startswith("repeated:"):
                nested[f["name"]] = t.split(":", 1)[1]
                out.append(f"    {f['name']}: {pt} = field(default_factory=list)")
            elif t == "map<string,string>":
                out.append(f"    {f['name']}: {pt} = field(default_factory=dict)")
            else:
                out.append(f"    {f['name']}: {pt} = {PY_DEFAULTS[t] if not t.startswith('enum:') else '0'}")
        if nested:
            out.append("")
            out.append("    _nested = {" + ", ".join(
                f'"{k}": {v}' for k, v in nested.items()) + "}")
        out.append("")
        out.append("")

    st = schema["streams"]
    out.append("class Stream:")
    out.append('    """Redis stream names and caps."""')
    out.append("")
    for key, s in st.items():
        out.append(f'    {key.upper()} = "{s["name"]}"')
    out.append("")
    out.append("")
    out.append("STREAM_MAXLEN = {")
    for s in st.values():
        out.append(f'    "{s["name"]}": {s["maxlen"]},')
    out.append("}")
    out.append("")
    out.append(f"SCHEMA_VERSION = {schema['version']}")
    out.append("")
    return "\n".join(out)


